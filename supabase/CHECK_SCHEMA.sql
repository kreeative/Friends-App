-- Is this database actually the schema the app was written against?
--
-- Every column every migration creates, checked in one query. Anything listed
-- is missing, and missing means some screen is quietly broken.
--
-- WHY THIS IS NEEDED AT ALL.
--
-- Two ways a Supabase project drifts from the files, and this project has hit
-- both. A script that fails halfway commits everything before the failure,
-- because the SQL editor runs statement by statement rather than in one
-- transaction. And a column added later to a file that was already run is
-- never picked up, because nobody re-runs 01_schema.sql.
--
-- That second one is what broke check-ins: `checkins.mood` was added to
-- 01_schema.sql after this database was created from it, submit_checkin writes
-- to that column, and every check-in failed with
--
--   [42703] column "mood" of relation "checkins" does not exist
--
-- An empty result means the schema is complete. Otherwise run
-- supabase/REPAIR.sql, which is idempotent, and check again.
-- ============================================================================
